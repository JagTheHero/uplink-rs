#!/usr/bin/env python3
"""Generate crates/engine/src/glut_fonts.rs from freeglut's src/fg_font_data.c.

    curl -sSfLo fg_font_data.c https://raw.githubusercontent.com/freeglut/freeglut/master/src/fg_font_data.c
    python3 tools/gen_glut_fonts.py fg_font_data.c > crates/engine/src/glut_fonts.rs

The glyphs are the X11 fonts GLUT's bitmap fonts were made from (XFree86/MIT licence, see the
header written below). Only characters 32..=126 and 160..=255 are kept: original GLUT 3.7 (the
glut32.dll the Windows game ships) has no glyphs for control characters.
"""
import re
import sys

src = open(sys.argv[1]).read()
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
arrays = {m.group(1): [int(x) for x in m.group(2).split(',') if x.strip()]
          for m in re.finditer(r'static const GLubyte (\w+)\[\] = \{([^}]*)\};', src)}
maps = {m.group(1): [x.strip() for x in m.group(2).split(',') if x.strip()]
        for m in re.finditer(r'static const GLubyte\* (\w+)\[\] = \{([^}]*)\};', src)}
fonts = {}
for m in re.finditer(r'SFG_Font (\w+) = \{ "([^"]*)", (\d+), (\d+), (\w+), (\d+), (\d+) \};', src):
    name, xname, _q, h, mp, xo, yo = m.groups()
    fonts[name] = (xname, int(h), int(xo), int(yo), [arrays.get(n) for n in maps[mp]])

order = [('FIXED_8X13', 'fgFontFixed8x13'), ('FIXED_9X15', 'fgFontFixed9x15'),
         ('TIMES_ROMAN_10', 'fgFontTimesRoman10'), ('TIMES_ROMAN_24', 'fgFontTimesRoman24'),
         ('HELVETICA_10', 'fgFontHelvetica10'), ('HELVETICA_12', 'fgFontHelvetica12'),
         ('HELVETICA_18', 'fgFontHelvetica18')]

print('''//! GLUT bitmap fonts (GLUT_BITMAP_8_BY_13, 9_BY_15, TIMES_ROMAN_10/24, HELVETICA_10/12/18).
//!
//! GENERATED by `tools/gen_glut_fonts.py` from freeglut's `src/fg_font_data.c`; do not edit.
//!
//! The glyphs come from the X11 fonts named below (XFree86 4.3.0). Licence of the data, as stated
//! in fg_font_data.c (XFree86 / MIT):
//!
//! Copyright (c) 1999-2000 by Pawel W. Olszta; portions copyright (c) 2004, the OpenGLUT project
//! contributors.
//!
//! Permission is hereby granted, free of charge, to any person obtaining a copy of this software
//! and associated documentation files (the "Software"), to deal in the Software without
//! restriction, including without limitation the rights to use, copy, modify, merge, publish,
//! distribute, sublicense, and/or sell copies of the Software, and to permit persons to whom the
//! Software is furnished to do so, subject to the following conditions:
//!
//! The above copyright notice and this permission notice shall be included in all copies or
//! substantial portions of the Software.
//!
//! THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING
//! BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND
//! NONINFRINGEMENT. IN NO EVENT SHALL PAWEL W. OLSZTA BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
//! LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN
//! CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE.
//!
//! Layout of `data`: for each character code 0..=255 one record
//! `[advance, bottom, rows, row bytes...]`, where `bottom` is the first non-empty row counted from
//! the bottom of the font's `height`-row cell, `rows` the number of rows kept, and every row is
//! `(advance + 7) / 8` bytes, MSB = leftmost pixel, bottom row first (glBitmap order). A record
//! `[0, 0, 0]` is a character GLUT has no glyph for. glutBitmapCharacter places the cell with
//! `glBitmap(advance, height, xorig, yorig, advance, 0, ...)`.

pub struct GlutFont {
    pub height: u8,
    pub xorig: u8,
    pub yorig: u8,
    pub data: &'static [u8],
}
''')
for rust, name in order:
    xname, h, xo, yo, glyphs = fonts[name]
    print('/// `%s`' % xname)
    print('#[rustfmt::skip]')
    print('pub static %s: GlutFont = GlutFont { height: %d, xorig: %d, yorig: %d, data: &[' % (rust, h, xo, yo))
    for code in range(256):
        g = glyphs[code] if code < len(glyphs) else None
        if g is None or code < 32 or 127 <= code < 160:
            print('    0, 0, 0,')
            continue
        w = g[0]
        bpr = (w + 7) // 8
        rows = [g[1 + r * bpr:1 + (r + 1) * bpr] for r in range(h)]
        nz = [i for i, r in enumerate(rows) if any(r)]
        if not nz:
            print('    %d, 0, 0, // %d' % (w, code))
            continue
        b, t = nz[0], nz[-1]
        flat = [x for r in rows[b:t + 1] for x in r]
        print('    %d, %d, %d, %s, // %d' % (w, b, t - b + 1, ', '.join(str(x) for x in flat), code))
    print(']};')
